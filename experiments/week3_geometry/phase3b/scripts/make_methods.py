"""Generate the Phase 3B classical-arm methods file FROM the Phase 3A one.

EXPLORATORY. Main project venv (numpy only).

The whole point of Phase 3B's classical experiments is that only ONE thing
changes relative to Phase 3A. That is only true if the shared settings are
literally the same object, not a retyped copy that could drift. So this script
reads `configs/phase3a_methods.json`, carries its `shared` and `flatport_params`
blocks across VERBATIM, records a hash of the source file, and appends only the
new configurations Phase 3B needs.

`configs/phase3a_methods.json` is NEVER modified.

    A    SIFT        + SIFT_BRUTEFORCE     carried across VERBATIM from Phase 3A, so the
                                          3B-4 frame-schedule runs are the same
                                          configuration and not a lookalike
    F2   SIFT        + SIFT_LIGHTGLUE      3B-1 matcher axis, SIFT features fixed
    F3   ALIKED_N32  + ALIKED_BRUTEFORCE   3B-1 matcher axis, ALIKED features fixed

F1 (= Phase 3A A) and F4 (= Phase 3A B) are REUSED from
`outputs/colmap/{A,B}/<clip>/run0`, not re-run.

Usage:
    .venv/bin/python -m experiments.week3_geometry.phase3b.scripts.make_methods
"""

from __future__ import annotations

import hashlib
import json
import os
import sys

REPO_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", "..", ".."))
W3 = os.path.join(REPO_ROOT, "experiments", "week3_geometry")
P3B = os.path.join(W3, "phase3b")

SRC = os.path.join(W3, "configs", "phase3a_methods.json")
DST = os.path.join(P3B, "configs", "phase3b_methods.json")

NEW_CONFIGS = {
    "F2": {
        "role": ("3B-1 matcher axis with SIFT features FIXED. Identical to Phase 3A "
                 "configuration A in every respect except the matcher type. F1->F2 is "
                 "therefore the matcher effect at constant feature representation."),
        "binary": "system_colmap",
        "extractor": "SIFT",
        "matcher_type": "SIFT_LIGHTGLUE",
        "refraction": None,
        "attribution_note": ("SIFT_LIGHTGLUE and ALIKED_LIGHTGLUE are DIFFERENT LightGlue "
                             "ONNX weights, and SIFT_BRUTEFORCE and ALIKED_BRUTEFORCE compare "
                             "different descriptors. The matcher axis this factorial measures "
                             "is 'nearest-neighbour matching vs the learned LightGlue matcher "
                             "trained for that descriptor', not one matcher applied to two "
                             "descriptors. That is the strongest factorial the installed "
                             "binary permits and every claim is scoped to it."),
    },
    "F3": {
        "role": ("3B-1 matcher axis with ALIKED_N32 features FIXED. Identical to Phase 3A "
                 "configuration B in every respect except the matcher type. F3->F4 is "
                 "therefore the matcher effect at constant learned feature representation."),
        "binary": "system_colmap",
        "extractor": "ALIKED_N32",
        "matcher_type": "ALIKED_BRUTEFORCE",
        "refraction": None,
        "extractor_note": ("ALIKED_N32, the same variant Phase 3A configuration B used, so "
                           "F3 -> F4 varies the matcher alone."),
    },
}


def main() -> int:
    with open(SRC, "rb") as fh:
        raw = fh.read()
    src = json.loads(raw)
    digest = hashlib.sha256(raw).hexdigest()

    out = {
        "_comment": ("Week 3 Phase 3B classical-arm configurations. GENERATED by "
                     "phase3b/scripts/make_methods.py from configs/phase3a_methods.json -- "
                     "do not hand-edit. The `shared` and `flatport_params` blocks are carried "
                     "across verbatim so that a Phase 3B run differs from its Phase 3A "
                     "counterpart in exactly the one field the hypothesis varies. Phase 3A's "
                     "config file is never modified and Phase 3A's outputs are never mutated."),
        "_generated_from": {
            "path": os.path.relpath(SRC, REPO_ROOT),
            "sha256": digest,
        },
        "_reused_from_phase3a": {
            "F1": "outputs/colmap/A/<clip>/run0  (SIFT + SIFT_BRUTEFORCE)",
            "F4": "outputs/colmap/B/<clip>/run0  (ALIKED_N32 + ALIKED_LIGHTGLUE)",
            "note": ("F1 and F4 are NOT re-run. Reusing them is what keeps the 2x2 factorial "
                     "cheap, and it is legitimate because the shared settings block below is "
                     "byte-identical to the one those runs used."),
        },
        "flatport_params": src["flatport_params"],
        "shared": src["shared"],
        "configs": {"A": dict(src["configs"]["A"], _carried_from_phase3a=True), **NEW_CONFIGS},
    }

    os.makedirs(os.path.dirname(DST), exist_ok=True)
    with open(DST, "w") as fh:
        json.dump(out, fh, indent=2)
    print(f"wrote {os.path.relpath(DST, REPO_ROOT)}")
    print(f"  source sha256 {digest}")
    print(f"  configs: {sorted(out['configs'])}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
